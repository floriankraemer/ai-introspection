// Generates src/api/schema.ts from the server's OpenAPI document.
// `node scripts/gen-api.mjs` writes it; `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import console from 'node:console';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';

const spec = fileURLToPath(new URL('../../docs/api/openapi.json', import.meta.url));
const out = fileURLToPath(new URL('../src/api/schema.ts', import.meta.url));

const raw =
  '/* eslint-disable */\n// Generated by scripts/gen-api.mjs from docs/api/openapi.json. Do not edit.\n' +
  astToString(await openapiTS(new URL(`file://${spec}`)));
const config = (await prettier.resolveConfig(out)) ?? {};
const next = await prettier.format(raw, { ...config, filepath: out });

if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== next) {
    console.error('src/api/schema.ts is stale: run `pnpm --filter web gen:api`');
    process.exit(1);
  }
} else {
  writeFileSync(out, next);
}
